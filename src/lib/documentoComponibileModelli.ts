// Nome e descrizione del modello nella lingua del sito
export function templateInfo(id: TemplateId, locale: string) {
  const d = dictOf(locale)
  return { name: d[SPECS[id].name], description: d[SPECS[id].description] }
}

// Documento pronto dal modello, nella lingua del sito
export function templateDocument(id: TemplateId, locale: string): DocContent {
  const d = dictOf(locale)
  const spec = SPECS[id]
  const blocks: DocBlock[] = spec.blocks.map((s) => {
    const b: DocBlock = { ...s, id: uid(), text: undefined, label: undefined, value: undefined, hint: undefined, options: undefined }
    if (s.text) b.text = d[s.text]
    if (s.label) b.label = d[s.label]
    if (s.value) b.value = d[s.value]
    if (s.hint) b.hint = d[s.hint]
    if (s.options) b.options = d[s.options]
    // Niente chiavi vuote nel documento salvato
    for (const k of Object.keys(b) as (keyof DocBlock)[]) if (b[k] === undefined) delete b[k]
    return b
  })
  return { title: d[spec.title], footer: d[spec.footer], blocks }
}
